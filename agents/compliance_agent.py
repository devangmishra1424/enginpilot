"""Compliance Agent (Playbook Section 5.4).

Checks whether described maintenance activities or asset states are
consistent with retrieved SOP requirements. Defaults to "Insufficient
Information" — a false "Compliant" verdict is worse than no answer at all.
"""

import re
from pathlib import Path

from agents import maintenance_agent
from agents.config import RETRIEVAL_CONFIDENCE_FLOOR
from agents.tools import qdrant_search
from llm import router

_PROMPT_PATH = Path(__file__).parent / "prompts" / "compliance.md"
_PROMPT_TEMPLATE = _PROMPT_PATH.read_text()

_CITATION_MARKER_PATTERN = re.compile(r"\b(section|clause|page)\b", re.IGNORECASE)


def _insufficient_info_answer(question: str, asset_class: str | None, why: str, what_would_help: str) -> str:
    # Insufficient Information template (Section 7.4): [What was searched] +
    # [Why it did not resolve] + [What would help, if known]. Matches the
    # Maintenance Agent's equivalent structure rather than a flat sentence.
    searched_for = asset_class or "the requested asset/maintenance-type"
    return (
        f"What was searched: SOP/manual clause content for {searched_for}, for the question: \"{question}\"\n"
        f"Why it did not resolve: {why}\n"
        f"What would help: {what_would_help}"
    )


def _classify_judgment(answer: str) -> str:
    lowered = answer.lower()
    if "not compliant" in lowered:
        return "not_compliant"
    if "insufficient information" in lowered:
        return "insufficient"
    if "compliant" in lowered:
        return "compliant"
    return "unknown"


def _has_specific_citation(answer: str, chunks: list[dict]) -> bool:
    lowered = answer.lower()
    if any(chunk["doc_name"].lower() in lowered for chunk in chunks):
        return True
    return bool(_CITATION_MARKER_PATTERN.search(answer))


def run(question: str, procedure_context: str | None = None) -> dict:
    """Returns {"answer": str, "source": list[dict] | None}.

    source=None means either no SOP was retrieved, or the LLM's "Compliant"
    verdict was rejected for lacking a specific citation (see the safety net
    below) — either way the orchestrator's source-check (Section 5.5) will
    turn this into "I don't have enough information."

    procedure_context (Demo Scenario 2, Section 12.2 step 4): when the
    Maintenance Agent has just produced a sourced procedure and the
    orchestrator is chaining straight into this agent to cross-check that
    specific procedure, its answer text is passed here so the judgment is
    made against THAT procedure rather than re-deriving one from scratch.
    When None (the normal, direct-question case), behavior is identical to
    calling this agent standalone — nothing about that path changes.
    """
    # Reuse the Maintenance Agent's asset/asset-class extraction — same
    # SOP-retrieval pattern, no need to duplicate the regex/keyword logic.
    asset_class = maintenance_agent.extract_asset_class(question)
    chunks = qdrant_search.search(query=question, asset_class=asset_class)

    if chunks and max(chunk["score"] for chunk in chunks) < RETRIEVAL_CONFIDENCE_FLOOR:
        # Confidence-gated answers guardrail (Section 7.3): a weak match is
        # treated exactly like no match at all — never answer from it.
        chunks = []

    if not chunks:
        # Section 5.4 escalation rule: defaults to Insufficient Information.
        # No LLM call.
        answer = _insufficient_info_answer(
            question,
            asset_class,
            why="No indexed SOP clause was found to check this activity/state against.",
            what_would_help="Acquiring or indexing a vendor manual or SOP document covering this asset class.",
        )
        return {"answer": answer, "source": None}

    if procedure_context is not None:
        question_for_prompt = (
            f"{question}\n\n"
            f"Procedure to check (generated by the Maintenance Agent):\n{procedure_context}"
        )
    else:
        question_for_prompt = question

    prompt = _PROMPT_TEMPLATE.format(chunks=chunks, question=question_for_prompt)
    answer = router.generate(prompt, role="articulation")

    judgment = _classify_judgment(answer)

    if judgment == "compliant" and not _has_specific_citation(answer, chunks):
        # CRITICAL SAFETY NET — Section 5.4 MVP KPI: zero false "Compliant"
        # verdicts. An LLM asserting compliance without pointing to a specific
        # clause is exactly the confident-but-unsupported answer Section 5.5
        # exists to prevent. Never trust an uncited "Compliant" — downgrade
        # regardless of what the LLM said. "Not Compliant" and genuinely
        # cited "Compliant" verdicts are not second-guessed beyond this check.
        answer = _insufficient_info_answer(
            question,
            asset_class,
            why=(
                "A relevant SOP clause was retrieved, but the judgment asserted \"Compliant\" "
                "without citing a specific clause to support it, so it cannot be trusted as-is."
            ),
            what_would_help=(
                "A judgment that explicitly cites the specific clause (document name + page) "
                "it's based on."
            ),
        )
        return {"answer": answer, "source": None}

    # The source is the actual retrieved chunk(s) the judgment was based on,
    # not a made-up citation.
    return {"answer": answer, "source": chunks}
